        // These eight weapons used their display name as their key, so in a "...Key" field the old
        // value has to become the new key, not the new display name. Runs before the general table.
        private static readonly (string Old, string New)[] KeyFieldRenames =
        {
            ("PMm", "PSh18Pchela"), ("MP7", "CorvanGnatPDW"), ("Protecta", "Tambour12"), ("SPSA14", "SP14Warden"),
            ("G36K", "HaldenHR36K"), ("IL86", "BR86Bulldog"), ("SKS", "SKNKarabin"), ("RPD", "RL44"),
        };

        public static string Apply(string json)
        {
            if (string.IsNullOrEmpty(json)) return json;
            foreach (var (o, n) in KeyFieldRenames)
                json = Regex.Replace(json, "(\"\\w*Key\"\\s*:\\s*\")" + Regex.Escape(o) + "\"", "${1}" + n + "\"");
            foreach (var (o, n) in Renames)
                json = json.Replace("\"" + o + "\"", "\"" + n + "\"");
            return json;
        }
    }
