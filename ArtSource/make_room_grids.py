# Generates GameCore/RoomGrids.cs from the "Room-grid" blocks in 06_Zone_Map.md (exact landmark
# layouts the design locks as canon). One char per cell:
#   # wall  . open  C light cover  = hard cover  ~ difficult  D door  ^ elevation  ! hazard
#   E entry/exit  H set-piece object (power core / hatch / vault)  T trader stall
import re, sys
src, dst = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8").read().split("\n")
TOK = {"#": "#", ".": ".", "C": "C", "=": "=", "~": "~", "D": "D", "^": "^", "!": "!", "H": "H", "TS": "T"}
grids = []
i = 0
while i < len(lines):
    m = re.match(r"> \*\*Room-grid: (.*?)\*\*", lines[i])
    if m:
        name = m.group(1); j = i + 1
        while "```" not in lines[j]: j += 1
        j += 2; rows = []
        while "```" not in lines[j]:
            toks = lines[j][1:].split()
            if toks and re.fullmatch(r"[A-Z]{1,2}", toks[0]):
                row = ""
                for t in toks[1:]:
                    t = t.rstrip(",")
                    if t.startswith("<-") or t.startswith("("): break
                    if re.fullmatch(r"E\d", t): row += "E"
                    elif t in TOK: row += TOK[t]
                    else: break
                rows.append(row)
            j += 1
        w = max(len(r) for r in rows)
        rows = [r.ljust(w, ".") for r in rows]
        grids.append((name, rows)); i = j
    i += 1
out = ["// GENERATED by ArtSource/make_room_grids.py from 06_Zone_Map.md's Room-grid blocks - the exact",
       "// landmark layouts the design locks as canon. One char per cell: # wall . open C light cover",
       "// = hard cover ~ difficult D door ^ elevation ! hazard E entry/exit H set-piece object T trader stall.",
       "// Stamped into zone recipes by TerrainCanvas.Stamp (ZoneLayoutBuilder.cs).",
       "using System.Collections.Generic;", "", "namespace GameCore", "{", "    public static class RoomGrids", "    {",
       "        public static readonly Dictionary<string, string[]> All = new Dictionary<string, string[]>", "        {"]
for name, rows in grids:
    out.append(f'            ["{name}"] = new[]')
    out.append("            {")
    out += [f'                "{r}",' for r in rows]
    out.append("            },")
out += ["        };", "    }", "}", ""]
open(dst, "w", encoding="utf-8").write("\n".join(out))
for n, r in grids: print(f"{n}: {len(r[0])}x{len(r)}"); [print("   ", x) for x in r]
