# The Abandoned Cathedral (Choir mission interior, 2026-11-20). Draws the plan as text (TierDungeons legend), checks every floor tile is reachable from the front door, writes
# Assets/Scripts/GameCore/TierDungeons.CathedralPlan.cs.   python3 ArtSource/plans/cathedral_plan.py
import os, sys
from collections import deque
W, H = 64, 54
g = [['#'] * W for _ in range(H)]
def rect(x0, y0, x1, y1, ch='.'):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): g[y][x] = ch
# --- the footprint (a cross): nave, aisles, transepts, apse, narthex
rect(20, 9, 43, 46)                 # nave
rect(13, 13, 19, 43); rect(44, 13, 50, 43)       # aisles
rect(5, 22, 58, 31)                 # transepts through the crossing
rect(24, 4, 39, 8)                  # apse
rect(24, 47, 39, 50)                # narthex
rect(26, 3, 37, 3)                  # the apse's rounded top
for x in (24, 25, 38, 39): g[4][x] = '#'
for x in (24, 39): g[5][x] = '#'
# --- pillar rows between the nave and the aisles (gaps between them so the aisles are reachable from the nave)
for y in range(14, 44, 3):
    if 21 <= y <= 31: continue
    g[y][19] = '+'; g[y][44] = '+'
# --- crossing pillars (big ones) and the bell rope
for (x, y) in ((23, 23), (40, 23), (23, 30), (40, 30)): g[y][x] = '+'
# --- pews: rows of desks either side of the centre aisle, the south half of the nave
for y in range(35, 45, 2):
    for x in list(range(22, 29)) + list(range(35, 42)): g[y][x] = 'd'
# --- choir stalls and the altar in the north
for y in range(11, 18, 2):
    for x in (21, 22, 41, 42): g[y][x] = 'd'
for x in range(29, 35): g[5][x] = 'h'
g[4][31] = 'h'; g[4][32] = 'h'
for x in (27, 36): g[6][x] = 'h'
# --- confessionals and side chapels in the aisles (hard cover)
for (x, y) in ((14, 16), (15, 16), (14, 40), (15, 40), (48, 16), (49, 16), (48, 40), (49, 40)): g[y][x] = 'h'
# --- windows in the outer walls (Solid 'n'), each with a spawn landmark floor tile just inside
wins = [(12, 17, 'F', 1), (12, 25, 'G', 1), (12, 33, 'H', 1), (12, 41, 'J', 1), (51, 17, 'K', -1), (51, 25, 'L', -1), (51, 33, 'M', -1), (51, 41, 'O', -1)]
# the transepts' west/east ends are y22..31 from x5/x58, so the aisle windows at y 17..41 sit on x=12 and x=51 where the aisle is (13..19/44..50)
for (x, y, ch, d) in wins:
    g[y][x] = 'n'; g[y][x + d] = ch
for y in (21,):
    pass
# transept end windows (north and south walls of the transept arms)
for x in (8, 12, 51, 55): g[21][x] = 'n'; g[32][x] = 'n'
# apse windows
for x in (27, 31, 36): g[3][x] = 'n'
# --- doors: the front door (E), the transept ends (P west, Q east)
g[53][31] = '#'
g[51][31] = 'D'; g[51][32] = 'D'; g[52][31] = 'E'
# narthex to nave opening is the whole width (rect already); the front door row:
for x in range(24, 40): g[51][x] = '#'
g[51][31] = 'D'; g[51][32] = 'D'
rect(30, 52, 33, 52, '.'); g[52][31] = 'E'
g[26][4] = 'D'; g[26][5] = 'P'; g[26][59] = 'D'; g[26][58] = 'Q'
# --- landmarks
g[27][31] = 'B'     # the bell rope at the crossing
g[6][31] = 'A'      # the altar steps
# sacristy: a small room off the apse's east side
rect(41, 4, 46, 8); g[6][40] = 'D'; g[6][41] = '.'; g[5][44] = 'R'
# crypt niche and a roost in the north aisles (blood-lured mutants)
rect(7, 14, 11, 18); g[16][12] = 'D'; g[16][11] = 'U'
rect(52, 14, 56, 18); g[16][51] = 'D'; g[16][52] = 'V'
# --- the mess: blood, bones, glass under the windows, papers
import random; rnd = random.Random(4)
def put(x, y, ch):
    if g[y][x] == '.': g[y][x] = ch
for _ in range(40): put(rnd.randint(21, 42), rnd.randint(10, 46), rnd.choice('*&\'~%'))
for (x, y, ch, d) in wins: put(x + 2 * d, y, ':'); put(x + 2 * d, y + 1, ':')
for _ in range(8): put(rnd.randint(6, 57), rnd.randint(23, 30), '"')
for x in range(28, 36):                 # blood and bones on the aisle runner before the altar
    put(x, 8, '*'); put(x, 9, '&')
# --- check reachability of every walkable tile from the front door
walk = set('.*&\'~%:";' + 'EBAPQRUVFGHJKLMO')
doors = set('D')
start = (31, 52)
seen = {start}; q = deque([start])
while q:
    x, y = q.popleft()
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        nx, ny = x + dx, y + dy
        if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and (g[ny][nx] in walk or g[ny][nx] in doors):
            seen.add((nx, ny)); q.append((nx, ny))
bad = [(x, y, g[y][x]) for y in range(H) for x in range(W) if g[y][x] in walk and (x, y) not in seen]
rows = [''.join(r) for r in g]
print('walkable', sum(1 for y in range(H) for x in range(W) if g[y][x] in walk), 'unreachable', len(bad), bad[:12])
if bad: sys.exit(1)
cs = ['// GENERATED by ArtSource/plans/cathedral_plan.py - do not edit by hand. The Abandoned Cathedral (the Choir mission, MISSION_CHOIR.md): the nave, aisles, transepts, apse, pillars, pews, windows.',
      'namespace GameCore', '{', '    public static partial class TierDungeons', '    {', '        public static readonly string[] CathedralPlan =', '        {']
cs += ['            "%s",' % r.replace('\\', '\\\\').replace('"', '\\"') for r in rows]
cs += ['        };', '    }', '}']
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Assets', 'Scripts', 'GameCore', 'TierDungeons.CathedralPlan.cs'), 'w').write('\n'.join(cs) + '\n')
print('\n'.join(rows))
