# Batch 92: writes Assets/Scripts/GameCore/TierDungeons.LabPlans.cs from the <id>.txt plans lab_plans.py made.
import os
here = os.path.dirname(os.path.abspath(__file__))
from lab_plans import LABS
from cave_plans import CAVES
from house_plans import HOUSES   # Batch 120
out = ["// Generated by ArtSource/plans/to_cs.py from lab_plans.py (Batch 92) - edit the generator, not this file.",
       "using System.Collections.Generic;", "", "namespace GameCore", "{", "    public static partial class TierDungeons", "    {",
       "        public static readonly Dictionary<string, string[]> LabPlans = new Dictionary<string, string[]>", "        {"]
for name in list(LABS) + ["hospital"] + list(CAVES) + list(HOUSES):
    rows = open(os.path.join(here, name + ".txt")).read().split("\n")
    out.append(f'            ["{name}"] = new[]')
    out.append("            {")
    out += ['                "' + r.replace('\\', '\\\\').replace('"', '\\"') + '",' for r in rows]
    out.append("            },")
out += ["        };", "    }", "}", ""]
open(os.path.join(here, "../../Assets/Scripts/GameCore/TierDungeons.LabPlans.cs"), "w").write("\n".join(out))
