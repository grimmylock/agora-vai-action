#!/usr/bin/env python3
"""The Hatch Tunnels (Tier 2 beat 1 "Taken", STORY.md): a big underground maze under the Loading Dock, one long corridor along its north side with the hidden lab's door in the middle of it, and the
mutants' nest at the corridor's far (east) end. Writes Assets/Scripts/GameCore/TierDungeons.TakenPlan.cs. Fixed seed: the same maze every run (the plan is data, like the other dungeons).
  python3 ArtSource/plans/taken_tunnels.py
Legend: # wall, . floor, E the hatch ladder (where you come down and where you run back to), F the lab door's spot in the corridor, H the nest, ! a steel door (the lab's, in the corridor's north wall)."""
import random, os, sys
SEED = int(os.environ.get('SEED', '71'))
W, H = 72, 52
CW, PITCH, X0, Y0, NX, NY = 3, 4, 2, 13, 17, 9          # maze cells: 3 wide, walls between them
g = [['#'] * W for _ in range(H)]
def carve(x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): g[y][x] = '.'
rnd = random.Random(SEED)
seen = {(NX - 1, NY - 1)}; stack = [(NX - 1, NY - 1)]
def cell(cx, cy): carve(X0 + cx * PITCH, Y0 + cy * PITCH, X0 + cx * PITCH + CW - 1, Y0 + cy * PITCH + CW - 1)
cell(NX - 1, NY - 1)
while stack:                                              # a recursive backtracker: one winding way with many dead ends
    cx, cy = stack[-1]; opts = [(cx + dx, cy + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if 0 <= cx + dx < NX and 0 <= cy + dy < NY and (cx + dx, cy + dy) not in seen]
    if not opts: stack.pop(); continue
    nx, ny = rnd.choice(opts); seen.add((nx, ny)); cell(nx, ny)
    ax, ay = X0 + min(cx, nx) * PITCH, Y0 + min(cy, ny) * PITCH
    if nx != cx: carve(ax + CW, ay, ax + CW, ay + CW - 1)  # the wall column between them
    else: carve(ax, ay + CW, ax + CW - 1, ay + CW)
    stack.append((nx, ny))
for _ in range(int(os.environ.get('LOOPS', '0'))):          # a few loops, so it is not a pure tree
    cx, cy = rnd.randrange(NX - 1), rnd.randrange(NY)
    ax, ay = X0 + cx * PITCH, Y0 + cy * PITCH; carve(ax + CW, ay, ax + CW, ay + CW - 1)
carve(6, 8, 63, 10)                                       # the long corridor, 3 wide, y 8-10
carve(2, 8, 5, 10); carve(2, 11, 4, 12)                   # its west end bends down into the maze's north-west cell (0, 0)
carve(64, 3, 70, 10)                                      # the nest at the far end
g[10 - 1][36] = '.'                                       # (the door sits in the wall row y = 7 above the corridor)
g[7][36] = '!'
g[9][36] = 'F'
g[7][67] = 'H'; g[7][67] = 'H'
ex, ey = X0 + (NX - 1) * PITCH + 1, Y0 + (NY - 1) * PITCH + 1; g[ey][ex] = 'E'
rows = [''.join(r) for r in g]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Assets', 'Scripts', 'GameCore', 'TierDungeons.TakenPlan.cs')
with open(out, 'w') as f:
    f.write('// GENERATED by ArtSource/plans/taken_tunnels.py - the Hatch Tunnels (Tier 2 beat 1 "Taken"): maze, long corridor, lab door, nest.\nusing System.Collections.Generic;\nusing GameData;\nusing static GameCore.GroundType;\n\nnamespace GameCore\n{\n    public static partial class TierDungeons\n    {\n        public static readonly string[] TakenPlan =\n        {\n')
    for r in rows: f.write(f'            "{r}",\n')
    f.write('''        };

        /// <summary>The maze under the Loading Dock: 'E' the hatch ladder (the way back up), 'F' the lab door's spot, 'H' the nest. Entered by the story (Tier2Story), not by an exit.</summary>
        public static MapLayout TakenTunnels()
        {
            var marks = new Dictionary<char, (string, string)> { ['E'] = ("Hatch Ladder", "industrial_basin"), ['F'] = ("Lab Door", null), ['H'] = ("Nest", null) };
            return FloorPlan("taken_tunnels", TakenPlan, "concrete", Concrete, marks, null);
        }
    }
}
''')
# BFS from E to the corridor's west end, to know how long the way is
from collections import deque
start = (ex, ey); goal = (6, 9); dist = {start: 0}; q = deque([start])
while q:
    x, y = q.popleft()
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        n = (x + dx, y + dy)
        if rows[n[1]][n[0]] != '#' and n not in dist: dist[n] = dist[(x, y)] + 1; q.append(n)
print('maze', W, 'x', H, ': the way from the ladder to the corridor is', dist.get(goal), 'tiles; reachable floor', len(dist), '; nest reachable only via corridor:', (67, 6) in dist)
