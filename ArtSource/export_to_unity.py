# Exports the art + faction data into the Unity project's formats:
#   Resources/Sprites/armor_atlas.png   - every faction armor (180), 16 per row, faction armband baked in
#   Resources/Sprites/mutant_atlas.png  - every mutant sprite (+ cloaked variants)
#   Scripts/GameData/FactionArmorDatabase.cs - 143 new ArmorDefs (merged into ArmorDatabase), faction
#                                              armor lines, weapon-category weights
#   Scripts/GameData/SpriteAtlasIndex.cs     - atlas cell order, read by GameCore/UnitSprites.cs
# Usage: python export_to_unity.py <path to ArmorDatabase.cs> <out dir>
import os, re, sys
from PIL import Image
import make_faction_armors as fa     # builds rows/imgs (and its own preview files) on import
import make_mutants as mu

ARMOR_DB_CS, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)
CELL, COLS = 16, 16

# Names in the design files that the game already ships under its own (renamed) identity.

# existing ArmorDatabase entries: Name -> (tierKey, key)
src = open(ARMOR_DB_CS, encoding="utf-8").read()
existing, tier = {}, None
for line in src.splitlines():
    m = re.search(r'\["(tier\d)"\]', line)
    if m: tier = m.group(1)
    m = re.search(r'\["(\w+)"\] = new ArmorDef \{ Name = "([^"]+)"', line)
    if m: existing[m.group(2)] = (tier, m.group(1))

def pascal(n):
    n = n.replace("'", "")
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", n) if w)

entries = {}   # game name -> dict
for fac, t, arch, name, st, look, is_orig in fa.rows:
    g = name
    if is_orig:
        assert g in existing, f"original armor not in ArmorDatabase.cs: {g}"
        tk, key = existing[g]
    else:
        tk, key = f"tier{t}", pascal(g)
        assert g not in existing and key not in {v[1] for v in existing.values()}, g
    entries[g] = dict(fac=fac, tier=t, arch=arch, tk=tk, key=key, st=st, new=not is_orig, src=name)

# ---- armor atlas with faction armband baked in (left shoulder: (5,8) light bodies, (4,7) heavy/exo) ----
order = [g for g in entries]
atlas = Image.new("RGBA", (COLS * CELL, ((len(order) + COLS - 1) // COLS) * CELL), (0, 0, 0, 0))
band_of = {f: v[0] for f, v in fa.FACTION.items()}
for i, g in enumerate(order):
    e = entries[g]
    img = fa.imgs[e["src"]].copy()
    band = band_of[[f for f in fa.FACTION if f == e["fac"]][0]]
    for x, y in ((5, 8), (4, 7)):
        r, gg, b, a = img.getpixel((x, y))
        if a and r + gg + b > 80:
            img.putpixel((x, y), fa.av.hexc(band)); break
    atlas.paste(img, ((i % COLS) * CELL, (i // COLS) * CELL))
atlas.save(os.path.join(OUT, "armor_atlas.png"))

m_order = [name for name, _, _, _ in mu.SPRITES]
matlas = Image.new("RGBA", (COLS * CELL, ((len(m_order) + COLS - 1) // COLS) * CELL), (0, 0, 0, 0))
for i, (_, _, img, _) in enumerate(mu.SPRITES):
    matlas.paste(img, ((i % COLS) * CELL, (i // COLS) * CELL))
matlas.save(os.path.join(OUT, "mutant_atlas.png"))

# ---- C# ----
def cs(s): return '"' + s.replace('"', '\\"') + '"'
L = []
L += ["// GENERATED by ArtSource/export_to_unity.py from the faction armor catalog",
      "// (ArtSource/02b_Faction_Armor_and_Weapons.md). Edit the catalog and re-run, don't hand-edit.",
      "//",
      "// 12 human factions x 5 tiers x 3 armors (Light / Standard / Heavy). The 37 original armors keep",
      "// their ArmorDatabase.cs entries; the 143 new ones below are merged into ArmorDatabase.Tiers by its",
      "// static constructor, so every existing lookup (Get, shop, loot, save/load by name) sees them.",
      "using System.Collections.Generic;", "using UnityEngine;", "", "namespace GameData", "{",
      "    public static partial class ArmorDatabase",
      "    {",
      "        static ArmorDatabase()",
      "        {",
      "            foreach (var (tier, key, def) in FactionArmorDatabase.NewArmors)",
      "                Tiers[tier][key] = def;",
      "        }",
      "    }", "",
      "    public static class FactionArmorDatabase",
      "    {",
      "        public static readonly (string tier, string key, ArmorDef def)[] NewArmors =",
      "        {"]
for g, e in entries.items():
    if not e["new"]: continue
    p, a, belt, mods, mp, kg, note = e["st"]
    extra = ", ImmuneToProne = true" if "Prone" in note else ""
    L.append(f'            ("{e["tk"]}", "{e["key"]}", new ArmorDef {{ Name = {cs(g)}, PhysDR = {p/100:.2f}f, AnomDR = {a/100:.2f}f, BeltSlots = {belt}, ModSlots = {mods}, Mp = {mp}, WeightKg = {kg}f{extra} }}),')
L += ["        };", "",
      "        private static readonly HashSet<string> NewKeys = new HashSet<string>",
      "        {",
      "            " + ", ".join(cs(e["key"]) for e in entries.values() if e["new"]),
      "        };", "",
      "        /// <summary>Faction-issue gear: dropped by / looted from that faction, not sold at general traders.</summary>",
      "        public static bool IsFactionIssue(string armorKey) => NewKeys.Contains(armorKey);", "",
      "        /// <summary>faction -> [tier 1..5] -> {Light, Standard, Heavy} ArmorDatabase keys.</summary>",
      "        public static readonly Dictionary<string, string[][]> Lines = new Dictionary<string, string[][]>",
      "        {"]
for fac in fa.CATALOG:
    gf = fac
    tiers = []
    for t in range(1, 6):
        tri = sorted([g for g, e in entries.items() if e["fac"] == gf and e["tier"] == t], key=lambda g: "LSH".index(entries[g]["arch"]))
        assert len(tri) == 3, (fac, t, tri)
        tiers.append("new[] { " + ", ".join(cs(entries[g]["key"]) for g in tri) + " }")
    L.append(f'            [{cs(gf)}] = new[] {{ {", ".join(tiers)} }},')
cats = ["melee", "sidearm", "smg", "shotgun", "assault", "sniper", "heavy"]
L += ["        };", "",
      "        /// <summary>Weapon category order for WeaponWeights.</summary>",
      "        public static readonly string[] WeaponCategories = { " + ", ".join(cs(c) for c in cats) + " };", "",
      "        /// <summary>d100 weights per faction - every faction fields every weapon type, these only set how common each is.</summary>",
      "        public static readonly Dictionary<string, int[]> WeaponWeights = new Dictionary<string, int[]>",
      "        {"]
for fac, w in fa.WEAPONS.items():
    L.append(f'            [{cs(fac)}] = new[] {{ {", ".join(map(str, w))} }},')
L += ["        };", "",
      "        // Factions that exist in FactionDatabase but have no gear line of their own.",
      "        private static readonly Dictionary<string, string> LineAliases = new Dictionary<string, string> { [\"Rookie\"] = \"Wanderers\" };", "",
      "        private static string LineFaction(string faction)",
      "        {",
      "            var f = FactionDatabase.NormalizeFactionName(faction);",
      "            return LineAliases.TryGetValue(f, out var alias) ? alias : f;",
      "        }", "",
      "        /// <summary>Armor tier band by rank (02b doc): Rookie/Experienced T1-2, Professional/Veteran",
      "        /// T2-3, Expert/Master T3-4, Legend T4-5 - never more than 1 above the zone's tier.</summary>",
      "        public static (int min, int max) ArmorTierRange(string rank, int zoneTier)",
      "        {",
      "            int min, max;",
      "            switch (rank)",
      "            {",
      "                case \"Professional\": case \"Veteran\": min = 2; max = 3; break;",
      "                case \"Expert\": case \"Master\": min = 3; max = 4; break;",
      "                case \"Legend\": min = 4; max = 5; break;",
      "                default: min = 1; max = 2; break;",
      "            }",
      "            max = System.Math.Max(1, System.Math.Min(max, zoneTier + 1));",
      "            return (System.Math.Min(min, max), max);",
      "        }", "",
      "        /// <summary>Faction armor for an NPC, or null if the faction has no line (caller falls back).",
      "        /// Leaders always get the Heavy variant.</summary>",
      "        public static ArmorDef PickArmor(string faction, string rank, int zoneTier, bool isLeader = false)",
      "        {",
      "            if (!Lines.TryGetValue(LineFaction(faction), out var line)) return null;",
      "            var (min, max) = ArmorTierRange(rank, zoneTier);",
      "            int tier = Random.Range(min, max + 1);",
      "            int variant = isLeader ? 2 : Random.Range(0, 3);",
      "            return ArmorDatabase.Get($\"tier{tier}\", line[tier - 1][variant]);",
      "        }", "",
      "        /// <summary>Weapon category rolled on the faction's weights, or null if the faction has none.</summary>",
      "        public static string PickWeaponCategory(string faction)",
      "        {",
      "            if (!WeaponWeights.TryGetValue(LineFaction(faction), out var w)) return null;",
      "            int roll = Random.Range(0, 100);",
      "            for (int i = 0; i < w.Length; i++)",
      "            {",
      "                if (roll < w[i]) return WeaponCategories[i];",
      "                roll -= w[i];",
      "            }",
      "            return WeaponCategories[WeaponCategories.Length - 1];",
      "        }",
      "    }", "}", ""]
open(os.path.join(OUT, "FactionArmorDatabase.cs"), "w", encoding="utf-8").write("\n".join(L))

A = ["// GENERATED by ArtSource/export_to_unity.py - cell order of Resources/Sprites/armor_atlas.png and",
     "// mutant_atlas.png (16x16 cells, 16 per row, left-to-right then top-to-bottom). Keyed by ArmorDef.Name /",
     "// MutantDef.Name; cloaked mutant variants are \"<Name> (cloaked)\". Read by GameCore/UnitSprites.cs.",
     "namespace GameData", "{", "    public static class SpriteAtlasIndex", "    {",
     f"        public const int Columns = {COLS};", "",
     "        public static readonly string[] Armor =", "        {"]
A += [f"            {cs(g)}," for g in order]
look_of = {r[3]: r[5] for r in fa.rows}
def glove(L):
    if L["head"] in ("sealed", "kokonmask"):                      # hazmat: gloves match the suit
        return "#%02x%02x%02x" % tuple(int(v * .8) for v in fa.av.hexc(L["S"])[:3])
    if L["body"] == "exo": return "#3a3c40"                         # metal gauntlets
    if L["head"] in ("bare", "bandit"): return "#c8916a"            # bare hands
    return "#3d4148"                                                # charcoal tactical gloves
A += ["        };", "", "        /// <summary>Floating-hand colours, same order as Armor: cuff = suit colour, glove per armor style.</summary>",
      "        public static readonly string[] ArmorCuff =", "        {"]
A += [f"            {cs(look_of[entries[g]['src']]['S'])}," for g in order]
A += ["        };", "", "        public static readonly string[] ArmorGlove =", "        {"]
A += [f"            {cs(glove(look_of[entries[g]['src']]))}," for g in order]
A += ["        };", "", "        public static readonly string[] Mutants =", "        {"]
A += [f"            {cs(n)}," for n in m_order]
A += ["        };", "    }", "}", ""]
open(os.path.join(OUT, "SpriteAtlasIndex.cs"), "w", encoding="utf-8").write("\n".join(A))
print("exported", len(order), "armors,", sum(e["new"] for e in entries.values()), "new;", len(m_order), "mutant sprites")

# Batch 24: the walk frames are derived from the atlas, so rebuild them with it
import make_walk_atlas
make_walk_atlas.build(OUT)
print("walk frames: armor_walk_a/b.png")
