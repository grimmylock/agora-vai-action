"""Optic mounts (2026-11-16): where each attachment sits on each gun's double-size picture (texture px) and which attachments each gun may take.
Yan's rules: PU 2x for the old rifles (Mosin and kin), ACOG 4x for the assault rifles and the modern long guns, an 8x for the modern snipers, red dots for sidearms AND SMGs, a laser for sidearms, shotguns nothing.
Writes Assets/Scripts/GameData/OpticMounts.cs. Mounts start from a heuristic (the receiver between the hands, the top/bottom outline there) with hand-set OVERRIDES after looking at the sheets (Tools/render/optic_sheet.py).
Run: python3 ArtSource/weapons/mounts.py"""
import re, sys, os
import numpy as np
from PIL import Image
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')); W = ROOT + '/Assets/Resources/Sprites/Weapons/'
src = open(ROOT + '/Assets/Scripts/GameCore/HeldWeapon.cs').read()
D = {k: float(v) for k, v in re.findall(r'\["(\w+)"\] = ([0-9.]+)f', re.search(r"Dense = new Dictionary<string, float>\s*\{(.*?)\};", src, re.S).group(1))}
G = {}
for k, row in re.findall(r'\["(\w+)"\] = new\[\] \{([^}]*)\}', re.search(r"Dictionary<string, float\[\]> Grips = new Dictionary<string, float\[\]>\s*\{(.*?)\n        \};", src, re.S).group(1)):
    G[k] = [float('nan') if 'NaN' in v else float(v.strip().rstrip('f')) for v in row.split(',')]
SIDEARM = ['PSh18Pchela', 'WaldenP9', 'Halden45Service', 'Corvan57', 'SR21Gadyuka', 'BlackHarrier', 'SteppeEagle', 'SperlingS96', 'HaldenServiceRevolver', 'RinaldiR6', 'RK12Kuvalda']
SMG = ['CorvanHornet45', 'CorvanWasp9', 'CorvanGnatPDW', 'VosaVz62', 'PPZZubr']
AK_OLD = ['VK74', 'VKM', 'VKS74U', 'NA94Yenisei']
ASSAULT_MODERN = ['VK74Obelisk', 'VK103', 'TR30', 'HaldenHR36K', 'BR86Bulldog', 'CorvanBattleRifle', 'CorvanBullpup', 'TS9Tishina', 'Smerch3']
SNIPER_OLD = ['M91Trekhlineyka', 'SKNKarabin', 'SV2Strela', 'VSNShepot', 'FrontierLeverRifle']
SNIPER_MODERN = ['CorvanMarksman', 'HaldenAM50Sledge', 'Sever98', 'VK127Grom', 'G7RailPrototype', 'Nightwalker4570']
ALLOWED = {}
for k in SIDEARM: ALLOWED[k] = ['reddot', 'laser']
for k in SMG: ALLOWED[k] = ['reddot', 'laser']                 # Yan: SMGs get lasers too
for k in AK_OLD + SNIPER_OLD: ALLOWED[k] = ['pu2']
for k in ASSAULT_MODERN: ALLOWED[k] = ['acog']
for k in SNIPER_MODERN: ALLOWED[k] = ['acog', 'scope8']
# overrides after review: key -> (topX, topY, underX, underY) in texture px; None keeps the heuristic value
OVERRIDES = {}
def sil(im):
    a = im[..., 3] > 0; top = np.array([np.argmax(a[:, x]) if a[:, x].any() else 10 ** 6 for x in range(a.shape[1])]); bot = np.array([a.shape[0] - 1 - np.argmax(a[::-1, x]) if a[:, x].any() else -1 for x in range(a.shape[1])])
    return a, top, bot
def heuristic(k):
    im = np.array(Image.open(W + f'weapon_{k}_hd.png').convert('RGBA')); a, top, bot = sil(im); xs = np.where(a.any(0))[0]; x0, x1 = xs.min(), xs.max(); L = x1 - x0; d = D[k]; g = G[k]
    if k in SIDEARM: tx = x0 + 0.40 * L
    elif g[2] == g[2]: tx = g[0] * d + 0.42 * (g[2] - g[0]) * d
    else: tx = x0 + 0.45 * L
    tx = int(round(tx))
    def solid_top(x, run=(6 if (k in SIDEARM or k in SMG) else 12)):                                                       # the first row with `run` solid pixels under it: skips sight posts, carry-handle arches and rail bumps
        for y in range(a.shape[0] - run):
            if a[y:y + run, x].all(): return y
        return int(top[x])
    ty = int(np.median([solid_top(x) for x in range(max(0, tx - (4 if (k in SIDEARM or k in SMG) else 16)), tx + (5 if (k in SIDEARM or k in SMG) else 17))]))
    # the laser hangs on the front of the frame, AHEAD of the trigger guard: find where the guard's front edge is (the last column in the middle of the gun whose underside is lower than the dust cover/barrel up front) and sit a laser's width in front of it
    far = (k in SMG)                                                                       # an SMG's barrel runs further past its foregrip and magazine, so look further forward
    base = int(np.median(bot[int(x0 + (0.90 if far else 0.80) * L):int(x0 + (0.97 if far else 0.92) * L) + 1])); mid = range(int(x0 + 0.25 * L), int(x0 + (0.90 if far else 0.80) * L))
    guard = [x for x in mid if bot[x] > base + 3]; gf = max(guard) if guard else int(x0 + 0.5 * L)
    ux = int(min(gf + 13, x1 - 12)); wb = bot[max(0, ux - 3):ux + 4]; uy = int(np.max(wb))
    return tx, ty, ux, uy
def main():
    rows = {}
    for k in ALLOWED:
        t = heuristic(k)
        if k in OVERRIDES: t = tuple(o if o is not None else h for o, h in zip(OVERRIDES[k], t))
        rows[k] = t
    ln = []
    ln.append('// GENERATED by ArtSource/weapons/mounts.py (2026-11-16): where an optic / under-barrel attachment sits on each gun, in TEXTURE px of the double-size picture, and what each gun may take. Do not edit by hand.')
    ln.append('using System.Collections.Generic;\nnamespace GameData\n{\n    public static class OpticMounts\n    {')
    ln.append('        /// <summary>topX, topY (the rail the optic sits on), underX, underY (the underside a laser hangs from).</summary>\n        public static readonly Dictionary<string, float[]> Mount = new Dictionary<string, float[]>\n        {')
    for k, t in rows.items(): ln.append(f'            ["{k}"] = new[] {{ {t[0]}f, {t[1]}f, {t[2]}f, {t[3]}f }},')
    ln.append('        };\n        public static readonly Dictionary<string, string[]> Allowed = new Dictionary<string, string[]>\n        {')
    for k, v in ALLOWED.items(): ln.append(f'            ["{k}"] = new[] {{ {", ".join(chr(34) + x + chr(34) for x in v)} }},')
    ln.append('        };\n    }\n}')
    open(ROOT + '/Assets/Scripts/GameData/OpticMounts.cs', 'w').write('\n'.join(ln) + '\n'); print(len(rows), 'guns')
if __name__ == '__main__': main()
